// The knowledge base behind the site lives in data/: one JSON file per block of content, with its notes.
// This tool turns it into data.js, the file the map and every page builder read.
//   node tools/build-data.js            rebuild data.js from data/core (run by build-static.js)
//   node tools/build-data.js --check    rebuild in memory and confirm it matches the data.js on disk
//   node tools/build-data.js --split    one-time move of data.js into data/core (already done; kept for reference)
// Edit data/core/*.json, never data.js: data.js is regenerated and any edit to it is overwritten.
"use strict";
const fs = require("fs"), path = require("path"), vm = require("vm");
const ROOT = path.join(__dirname, ".."), CORE = path.join(ROOT, "data", "core"), OUT = path.join(ROOT, "data.js");
const MANIFEST = path.join(CORE, "manifest.json");

const HEADER = `/* ==========================================================
   THE MAP'S CONTENT, GENERATED
   Built by tools/build-data.js from the knowledge base in data/core/.
   Do not edit this file: change data/core/<NAME>.json (and its
   notes in data/core/manifest.json), then run
   node tools/build-data.js, or the whole site build.
   Written compactly, one block per line, because every visitor
   downloads it: the readable copy of each block, with its notes,
   is data/core/<NAME>.json and data/core/manifest.json.
   ========================================================== */
`;

function load(src) {
  const names = [...src.matchAll(/^const ([A-Z_][A-Z0-9_]*)\s*=/gm)].map(m => m[1]);
  const c = {}; vm.createContext(c);
  vm.runInContext(src + `;this.__V={${names.join(",")}}`, c);
  return { names, values: c.__V };
}

// readable JSON: short arrays of plain values on one line, everything else indented
function ser(v, ind = "") {
  const next = ind + "  ";
  if (Array.isArray(v)) {
    if (!v.length) return "[]";
    if (v.every(x => x === null || typeof x !== "object")) { const one = JSON.stringify(v); if (one.length < 110) return one; }
    return "[\n" + v.map(x => next + ser(x, next)).join(",\n") + "\n" + ind + "]";
  }
  if (v && typeof v === "object") {
    const ks = Object.keys(v); if (!ks.length) return "{}";
    return "{\n" + ks.map(k => next + JSON.stringify(k) + ": " + ser(v[k], next)).join(",\n") + "\n" + ind + "}";
  }
  return JSON.stringify(v);
}

function split() {
  const src = fs.readFileSync(OUT, "utf8"), lines = src.split("\n");
  const { names, values } = load(src);
  const starts = names.map(n => lines.findIndex(l => l.startsWith(`const ${n} `) || l.startsWith(`const ${n}=`)));
  fs.mkdirSync(CORE, { recursive: true });
  const manifest = [];
  names.forEach((n, i) => {
    // notes: the comment lines just above the block, plus any comment lines inside it
    let j = starts[i] - 1; const above = [];
    while (j >= 0) {
      const t = lines[j].trim();
      if (t === "" || t.startsWith("//")) { above.unshift(lines[j]); j--; continue; }
      if (t.endsWith("*/")) {                       // a whole block comment, however its middle lines look
        let k = j; while (k >= 0 && !lines[k].includes("/*")) k--;
        above.unshift(...lines.slice(k, j + 1)); j = k - 1; continue;
      }
      break;
    }
    const end = i + 1 < names.length ? starts[i + 1] : lines.length;
    const inside = lines.slice(starts[i] + 1, end).filter(l => /^\s*(\/\/|\/\*)/.test(l) && !above.includes(l)).map(l => l.trim());
    const notes = above.join("\n").replace(/^\s+|\s+$/g, "").replace(/^\/\* =+[\s\S]*?=+ \*\/\s*/, "");   // the file header is replaced by the generated one
    manifest.push({ name: n, file: `${n}.json`, notes, inside });
    fs.writeFileSync(path.join(CORE, `${n}.json`), ser(values[n]) + "\n");
  });
  fs.writeFileSync(MANIFEST, JSON.stringify(manifest, null, 1) + "\n");
  console.log(`split: ${names.length} blocks into data/core`);
}

// one compact line per block, each starting "const NAME = " so the page builders can find the blocks by name
function build() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, "utf8"));
  let out = HEADER;
  for (const m of manifest) {
    if (m.browser === false) continue;   // build-only: builders read it from data/core (tools/data-blocks.js); browsers never download it
    const v = JSON.parse(fs.readFileSync(path.join(CORE, m.file), "utf8"));
    out += `const ${m.name} = ${JSON.stringify(v)};\n`;
  }
  return out;
}

// Nearest places to act (HARM_HOPE): every harm that no lever touches is listed, with levers that exist and sit within
// two links of it on the map, or [] for an honest gap. Harms that gain a lever of their own drop out of the list.
function checkHope(V) {
  if (!V.HARM_HOPE) return [];
  const problems = [], levers = Object.fromEntries(V.LEVERS.map(v => [v.id, v])), harms = new Set(V.CONSEQUENCES.map(c => c.id));
  const touched = new Set(V.LEVERS.flatMap(v => v.edge));
  const adj = {}; V.LINKS.forEach(([a, b]) => { (adj[a] = adj[a] || []).push(b); (adj[b] = adj[b] || []).push(a); });
  const within2 = id => { const s = new Set([id]); (adj[id] || []).forEach(x => { s.add(x); (adj[x] || []).forEach(y => s.add(y)); }); return s; };
  V.CONSEQUENCES.forEach(c => { if (!touched.has(c.id) && !(c.id in V.HARM_HOPE)) problems.push(`HARM_HOPE: "${c.id}" has no lever and no entry`); });
  for (const [id, ls] of Object.entries(V.HARM_HOPE)) {
    if (!harms.has(id)) { problems.push(`HARM_HOPE: "${id}" is not a harm on the map`); continue; }
    if (touched.has(id)) problems.push(`HARM_HOPE: "${id}" now has a lever of its own; remove its entry`);
    if (!Array.isArray(ls)) { problems.push(`HARM_HOPE: "${id}" needs a list`); continue; }
    const near = within2(id);
    ls.forEach(l => {
      if (!levers[l]) problems.push(`HARM_HOPE: "${id}" lists unknown lever "${l}"`);
      else if (!levers[l].edge.some(e => near.has(e))) problems.push(`HARM_HOPE: "${id}" lists "${l}", which is more than two links away`);
    });
  }
  return problems;
}
// The homepage's open and folded sections (HOME_OPEN, SECTION_SUMMARIES): every id is a section on the homepage,
// none is both open and folded, and every label is a short line.
function checkHome(V) {
  if (!V.HOME_OPEN || !V.SECTION_SUMMARIES) return [];
  const html = fs.readFileSync(path.join(ROOT, "index.html"), "utf8"), problems = [];
  const sections = new Set([...html.matchAll(/<section\b[^>]*\bid="([^"]+)"/g)].map(m => m[1]));
  V.HOME_OPEN.open.forEach(id => { if (!sections.has(id)) problems.push(`HOME_OPEN: "${id}" is not a section on the homepage`); });
  Object.entries(V.SECTION_SUMMARIES).forEach(([id, label]) => {
    if (!sections.has(id)) problems.push(`SECTION_SUMMARIES: "${id}" is not a section on the homepage`);
    if (V.HOME_OPEN.open.includes(id)) problems.push(`"${id}" is both open (HOME_OPEN) and folded (SECTION_SUMMARIES)`);
    if (!label || label.length > 40) problems.push(`SECTION_SUMMARIES: "${id}" needs a short button label`);
  });
  V.HOME_OPEN.open.forEach(id => { if (!(V.HOME_OPEN.why || {})[id]) problems.push(`HOME_OPEN: "${id}" needs its reason in why`); });
  // one story: every open section keeps the shared anatomy (class "story", a header.story__head with an h2.story__h)
  V.HOME_OPEN.open.forEach(id => {
    const m = html.match(new RegExp(`<section\\b[^>]*\\bid="${id}"[^>]*>([\\s\\S]*?)</section>`)); if (!m) return;
    if (!/\bclass="[^"]*\bstory\b/.test(m[0].slice(0, m[0].indexOf(">")))) problems.push(`index.html #${id}: an open section needs class "story" (see .story in styles.css)`);
    if (!/<header class="story__head\b[\s\S]*?class="[^"]*\bstory__h\b/.test(m[1])) problems.push(`index.html #${id}: needs <header class="story__head"> with its headline as <h2 class="h2 story__h">`);
  });
  // calm by default: only these animations may loop forever (the live ticker, and loops that answer a click or show loading)
  const LOOPS_OK = [".edge.flow", ".lever.on .lever__ring", ".ticker__track", ".ticker .ticker__track", ".atl-hw.is-now", ".lv-spin"];
  const css = fs.readFileSync(path.join(ROOT, "styles.css"), "utf8").replace(/\/\*[\s\S]*?\*\//g, "");
  for (const r of css.matchAll(/([^{}]+)\{([^{}]*)\}/g)) { const sel = r[1].trim(); if (!/\binfinite\b/.test(r[2])) continue;
    if (!LOOPS_OK.includes(sel)) problems.push(`styles.css: "${sel}" loops forever; let it run a few times and rest (e.g. "3" instead of "infinite"), or add it to LOOPS_OK in tools/build-data.js if a reader's action starts it`); }
  return problems;
}
// Watch-outs (LEVERS watch): each documented side effect of a lever is a short sentence with at least one source that
// has a label and an https link, so a reader can check it. Each problem names the lever and what to fix.
function checkWatch(V) {
  const P = [];
  (V.LEVERS || []).forEach(v => { if (v.watch === undefined) return;
    if (!Array.isArray(v.watch) || !v.watch.length) return P.push(`LEVERS ${v.id}: watch must be a list of { text, sources }, or left out`);
    v.watch.forEach((w, i) => { const at = `LEVERS ${v.id} watch[${i}]`;
      if (!w.text || w.text.length > 320) P.push(`${at}: needs text of at most 320 characters`);
      if (!(w.sources || []).length) P.push(`${at}: needs at least one source`);
      (w.sources || []).forEach(x => { if (!x.label || !/^https:\/\//.test(x.url || "")) P.push(`${at}: each source needs a label and an https url`); }); }); });
  return P;
}
// Social protection (SOCIAL_PROTECTION, one file per country in data/social-protection/): unique ids, fixed values from
// the README, an as-of date on every scheme, https sources, ladder steps from the eight, links that resolve, and no
// em dash. Each problem names the country, the record and what to fix.
// Watch Common Shade grow (data/site/growth.json): one reviewed entry per change. Kinds, roots, places, people and
// topics come from fixed lists; every link, page and action resolves; "why" is one or two sentences; a quoted finding
// appears word for word in the site's own records; effort files exist; nothing vague like "Learn more". Each problem
// names the entry and the field.
// The learning agenda (data/site/learning.json): every question has a dated history whose latest step is its status;
// advanced and answered steps name the records that moved them and have a matching change on /growing/.
function checkLearning(V) {
  const fs = require("fs"), path = require("path"), ROOT = path.join(__dirname, ".."), P = [];
  const L = JSON.parse(fs.readFileSync(path.join(ROOT, "data/site/learning.json"), "utf8")), today = new Date().toISOString().slice(0, 10);
  const G = fs.existsSync(path.join(ROOT, "data/site/growth.json")) ? JSON.parse(fs.readFileSync(path.join(ROOT, "data/site/growth.json"), "utf8")).entries : [];
  const deepIds = x => Array.isArray(x) ? x.flatMap(deepIds) : x && typeof x === "object" ? [x.id, ...Object.values(x).flatMap(deepIds)] : [];
  const known = new Set([...deepIds(V.EVIDENCE), ...deepIds(V.LEVERS),
    ...fs.readdirSync(path.join(ROOT, "data/kb")).filter(f => f.endsWith(".json") && !f.startsWith("_")).flatMap(f => JSON.parse(fs.readFileSync(path.join(ROOT, "data/kb", f), "utf8")).map(r => r.id))].filter(Boolean));
  const ids = new Set();
  L.questions.forEach(q => { const at = `data/site/learning.json question ${q.id}`, h = q.history || [];
    if (ids.has(q.id)) P.push(`${at}: id used twice`); ids.add(q.id);
    if (!h.length) { P.push(`${at}: needs a history, starting with { date, status: "open", note } on the day it appeared`); return; }
    if (h[0].status !== "open") P.push(`${at}: the first history step is "open"`);
    h.forEach((s, i) => { const st = `${at} history step ${i + 1}`;
      if (!/^\d{4}-\d{2}-\d{2}$/.test(s.date || "") || s.date > today) P.push(`${st}: date must be a past date, YYYY-MM-DD`);
      if (i && s.date < h[i - 1].date) P.push(`${st}: steps run in date order`);
      if (!["open", "advanced", "answered"].includes(s.status)) P.push(`${st}: status must be open, advanced or answered`);
      if (!s.note) P.push(`${st}: needs a short note`);
      if (s.status !== "open") {
        if (!(s.records || []).length) P.push(`${st}: an ${s.status} step names the record ids that moved it`);
        (s.records || []).forEach(r => { if (!known.has(r)) P.push(`${st}: record "${r}" is not in EVIDENCE or data/kb`); });
        if (!G.some(e => e.kind === "question-advanced" && e.question === q.id && e.added === s.date)) P.push(`${st}: add a "question-advanced" change to data/site/growth.json with "question": "${q.id}" and "added": "${s.date}"`);
      } });
    (q.underway || []).forEach((u, i) => { const st = `${at} underway ${i + 1}`;
      if (!/^\d{4}-\d{2}-\d{2}$/.test(u.since || "") || u.since > today) P.push(`${st}: since must be a past date, YYYY-MM-DD`);
      if (!u.text) P.push(`${st}: needs text saying what the work is`);
      if (!Array.isArray(u.source) || !u.source[0] || !/^https?:\/\//.test(u.source[1] || "")) P.push(`${st}: source is ["label", "https://..."]`); });
    if (q.status !== h[h.length - 1].status) P.push(`${at}: status "${q.status}" differs from its latest history step "${h[h.length - 1].status}"`);
  });
  G.filter(e => e.kind === "question-advanced").forEach(e => { const q = L.questions.find(x => x.id === e.question);
    if (!q) P.push(`data/site/growth.json entry ${e.id}: "question" must be a learning.json question id`);
    else if (!(q.history || []).some(s => s.status !== "open" && s.date === e.added)) P.push(`data/site/growth.json entry ${e.id}: ${e.question} has no advanced or answered step dated ${e.added}`); });
  return P;
}
