// Writes each short film's page and narration from shorts.js, in the style of tools/films.
//   node tools/shorts/build.js            pages and narration files for every short
//   node tools/shorts/build.js delhi      just those whose id contains "delhi"
// Then voice and render each (see README.md): narrate.py and render.js, with FILM_DIR=tools/shorts FILM_OUT=shorts.
"use strict";
const fs = require("fs"), path = require("path");
const { SCENES, ICONS } = require("./art");
const SHORTS = require("./shorts");
const esc = s => String(s ?? "").replace(/[&<>"]/g, c => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;" }[c]));
const VOICE = { model: "en-us-libritts-high", speaker: 599, length_scale: 0.94, licence: "LibriTTS (CC BY 4.0), via the Piper voice en-us-libritts-high" };

const CSS = fs.readFileSync(path.join(__dirname, "film.css"), "utf8");
const MARK = `<svg width="36" height="28" viewBox="0 0 26 20"><path d="M2.5 8 Q13 -1 23.5 8" fill="none" stroke="#F26430" stroke-width="4" stroke-linecap="round"/><path d="M6.5 7 V18.5 M19.5 7 V18.5" stroke="#F6E7D7" stroke-width="2.4" stroke-linecap="round"/></svg>COMMON SHADE`;
const CANOPY = `<svg class="art" viewBox="0 0 520 520" style="right:90px;bottom:120px;width:460px;height:400px">
    <path class="of unfurl" style="--d:.4s" d="M40 150 Q260 60 480 150 L480 170 Q260 84 40 170 Z"/>
    <g class="fade" style="--d:.2s"><path d="M60 166 V430 M460 166 V430 M30 430 H490"/>
      <circle cx="110" cy="300" r="18"/><path d="M110 318 V376 L92 430 M110 376 L128 430 M110 336 L66 300"/>
      <circle cx="410" cy="300" r="18"/><path d="M410 318 V376 L392 430 M410 376 L428 430 M410 336 L454 300"/>
      <circle cx="250" cy="330" r="16"/><path d="M250 346 V392 L234 430 M250 392 L266 430"/><circle cx="290" cy="360" r="11"/><path d="M290 371 V400 L280 430 M290 400 L300 430 M290 380 L262 372"/></g></svg>`;
const art = name => `<svg class="art" viewBox="0 0 520 520">${(SCENES[name] || SCENES.sun)()}</svg>`;
const url = page => "beattheheat.asia/" + page.replace(/index\.html$/, "");

function scene(s, i, f) {
  const k = s.k ? `<p class="k in" style="--d:.2s">${esc(s.k)}</p>` : "";
  if (s.t === "title") return `<section class="s">${k}<h1 class="in" style="--d:.4s">${esc(s.h)}</h1>${s.sub ? `<p class="serif in" style="--d:1s">${esc(s.sub)}</p>` : ""}${art(s.art)}</section>`;
  if (s.t === "stat") return `<section class="s">${k}<p class="big in" style="--d:.5s">${esc(s.n)}</p><p class="p in" style="--d:1.1s">${esc(s.p)}</p>${art(s.art)}</section>`;
  if (s.t === "point") return `<section class="s">${k}<h2 class="in" style="--d:.4s">${esc(s.h)}</h2><p class="p in" style="--d:1s">${esc(s.p)}</p>${art(s.art)}</section>`;
  if (s.t === "three") return `<section class="s">${k}<h2 class="in" style="--d:.3s;max-width:none">${esc(s.h)}</h2><div class="three">${s.cards.map((c, j) =>
    `<div class="card in" data-beat="${j + 1}" style="--d:${(1 + j * 1.2).toFixed(1)}s"><svg viewBox="0 0 300 150">${ICONS[c.i] || ""}</svg><b>${esc(c.b)}</b><span>${esc(c.s)}</span></div>`).join("")}</div></section>`;
  if (s.t === "close") return `<section class="s s--last night">${CANOPY}${k.replace('class="k', 'class="k k--night')}<p class="serif in" style="--d:.7s;font-size:48px;max-width:640px;margin-top:28px">${esc(s.line)}</p>` +
    `<p class="src fade" style="--d:1.2s"><b>${esc(url(f.page))}</b><br>Sources: ${esc(f.sources)}.</p><p class="mark fade" style="--d:1.2s">${MARK}</p></section>`;
  throw new Error(`${f.id}: unknown scene type ${s.t}`);
}

const only = process.argv[2];
for (const f of SHORTS.filter(f => !only || f.id.includes(only))) {
  const html = `<!DOCTYPE html>
<!-- "${f.title}": a short drawn film for /${f.page.replace(/index\.html$/, "")}. Generated by tools/shorts/build.js from shorts.js; edit there.
     Rendered frame by frame by tools/films/render.js. Drawn, faceless figures only. -->
<html lang="en"><head><meta charset="UTF-8"><title>${esc(f.title)}</title><style>${CSS}</style></head><body>
${f.scenes.map((s, i) => scene(s, i, f)).join("\n")}
</body></html>
`;
  fs.writeFileSync(path.join(__dirname, f.id + ".html"), html);
  fs.writeFileSync(path.join(__dirname, f.id + ".narration.json"), JSON.stringify({ voice: VOICE, scenes: f.scenes.map(s => s.say) }, null, 1) + "\n");
}
console.log("shorts: wrote", SHORTS.filter(f => !only || f.id.includes(only)).length, "film pages");
